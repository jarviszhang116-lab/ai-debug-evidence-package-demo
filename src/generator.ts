import {
  DebugEvidencePackage,
  ActionStep,
  NetworkFailure,
  ConsoleError,
  DomSnapshot,
  EnvironmentInfo,
  generatePackageId,
  detectFailureType,
  redactValue
} from './types';

export function generateMarkdownPackage(pkg: DebugEvidencePackage): string {
  const lines: string[] = [];

  lines.push('# AI Debug Evidence Package');
  lines.push('');
  lines.push('## 基本信息');
  lines.push(`- **Package ID**: ${pkg.id}`);
  lines.push(`- **时间**: ${pkg.timestamp}`);
  lines.push(`- **URL**: ${pkg.url}`);
  lines.push(`- **失败类型**: ${pkg.failureType}`);
  lines.push(`- **摘要**: ${pkg.summary}`);
  lines.push('');

  lines.push('## 操作序列');
  if (pkg.actionSequence.length === 0) {
    lines.push('无记录');
  } else {
    pkg.actionSequence.forEach((step, idx) => {
      const time = new Date(step.timestamp).toISOString();
      lines.push(`${idx + 1}. [${time}] ${step.type.toUpperCase()}: ${step.detail}`);
      if (step.selector) lines.push(`   - 选择器: \`${step.selector}\``);
      if (step.value) lines.push(`   - 值: ${step.value}`);
    });
  }
  lines.push('');

  lines.push('## DOM 快照');
  if (pkg.domSnapshot.formSelector) {
    lines.push(`- 表单选择器: \`${pkg.domSnapshot.formSelector}\``);
  }
  if (pkg.domSnapshot.submitButton) {
    lines.push(`- 提交按钮: \`${pkg.domSnapshot.submitButton.selector}\` (文本: "${pkg.domSnapshot.submitButton.text}")`);
  }
  if (pkg.domSnapshot.relevantFields && pkg.domSnapshot.relevantFields.length > 0) {
    lines.push('- 相关字段:');
    pkg.domSnapshot.relevantFields.forEach(field => {
      lines.push(`  - ${field.name} (\`${field.selector}\`): 类型=${field.type}, 值长度=${field.valueLength}`);
    });
  }
  lines.push('');

  lines.push('## Console 错误');
  if (pkg.consoleErrors.length === 0) {
    lines.push('无');
  } else {
    pkg.consoleErrors.forEach(err => {
      lines.push(`- ${err.message}`);
      if (err.stack) {
        lines.push('  ```');
        lines.push(`  ${err.stack.split('\n').slice(0, 5).join('\n  ')}`);
        lines.push('  ```');
      }
    });
  }
  lines.push('');

  lines.push('## 失败网络请求');
  if (pkg.networkFailures.length === 0) {
    lines.push('无');
  } else {
    pkg.networkFailures.forEach(net => {
      lines.push(`- **${net.method}** \`${net.url}\``);
      lines.push(`  - Status: ${net.status} ${net.statusText}`);
      lines.push(`  - 耗时: ${net.duration}ms`);
      if (net.responseSnippet) {
        lines.push(`  - 响应片段: ${net.responseSnippet}`);
      }
    });
  }
  lines.push('');

  lines.push('## 环境信息');
  lines.push(`- Browser: ${pkg.environment.browser}`);
  lines.push(`- OS: ${pkg.environment.os}`);
  lines.push(`- Viewport: ${pkg.environment.viewport}`);
  lines.push(`- User Agent: ${pkg.environment.userAgent}`);
  lines.push('');

  lines.push('## 建议优先查看');
  lines.push(generateSuggestions(pkg));
  lines.push('');

  lines.push('---');
  lines.push('*Generated by AI Debug Evidence Package*');

  return lines.join('\n');
}

function generateSuggestions(pkg: DebugEvidencePackage): string {
  const suggestions: string[] = [];

  if (pkg.failureType.includes('404')) {
    suggestions.push('1. 检查生产环境路由是否正确部署');
    suggestions.push('2. 对比本地与生产的 API 路径配置');
  } else if (pkg.failureType.includes('Authorization')) {
    suggestions.push('1. 检查登录态 / Cookie / Session 是否正常携带');
    suggestions.push('2. 确认跨域或 SameSite 配置');
    suggestions.push('3. 查看特定浏览器环境（如微信内置浏览器）的兼容性');
  } else if (pkg.failureType.includes('Validation')) {
    suggestions.push('1. 对比前端与后端的校验规则是否一致');
    suggestions.push('2. 检查必填字段与格式要求');
  } else if (pkg.failureType.includes('Server Error')) {
    suggestions.push('1. 查看服务端日志中的对应错误');
    suggestions.push('2. 确认相关 API 是否正常运行');
  } else if (pkg.consoleErrors.length > 0) {
    suggestions.push('1. 根据 Console 错误定位前端代码');
    suggestions.push('2. 检查是否有未捕获的异常影响提交');
  } else {
    suggestions.push('1. 查看失败网络请求的详细响应');
    suggestions.push('2. 确认表单提交目标 URL 是否正确');
  }

  return suggestions.join('\n');
}

export function buildPackage(params: {
  url: string;
  actionSequence: ActionStep[];
  consoleErrors: ConsoleError[];
  networkFailures: NetworkFailure[];
  domSnapshot: DomSnapshot;
  environment: EnvironmentInfo;
  summary?: string;
}): DebugEvidencePackage {
  const failureType = detectFailureType(params.networkFailures, params.consoleErrors);
  const summary = params.summary || `${failureType} on form submission at ${params.url}`;

  return {
    id: generatePackageId(),
    timestamp: new Date().toISOString(),
    failureType,
    url: params.url,
    actionSequence: params.actionSequence,
    consoleErrors: params.consoleErrors,
    networkFailures: params.networkFailures,
    domSnapshot: params.domSnapshot,
    environment: params.environment,
    summary
  };
}
